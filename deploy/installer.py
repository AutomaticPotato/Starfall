#!/usr/bin/env python3
"""Implementation of setup.sh; only Python's standard library is required."""
import argparse
import errno
import fcntl
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import secrets
import shutil
import signal
import socket
import stat
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request

GIB = 1024 ** 3
SECRET_KEYS = ('STARLIGHTS_SA_PASSWORD', 'STARLIGHTS_ADMIN_KEY', 'STARLIGHTS_MASTER_PASSWORD')
FOLDERS = ('portraits', 'homebrew', 'content', 'lore', 'mssql', 'art')


class SetupError(Exception):
    pass


def emit(message):
    print(message, flush=True)


def read_env(path):
    """A deliberately literal subset shared with Compose and admin.sh; never source a shell file."""
    if path.is_symlink() or not path.is_file():
        raise SetupError('.env must be a regular file, not a symbolic link.')
    if path.stat().st_uid != os.getuid() or stat.S_IMODE(path.stat().st_mode) != 0o600:
        raise SetupError('.env must belong to your user and have mode 600. Run chmod 600 .env as its owner.')
    values = {}
    for line in path.read_text(encoding='utf-8-sig').splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        match = re.fullmatch(r'([A-Z][A-Z0-9_]*)=([A-Za-z0-9_./+!=:@%\-]*)', line)
        if not match or match[1] in values:
            raise SetupError('.env has a duplicate or unsupported assignment. Use one KEY=value per line, '
                             'without quotes, spaces or variable substitutions; existing secrets were not changed.')
        values[match[1]] = match[2]
    if any(not values.get(key) for key in SECRET_KEYS):
        raise SetupError('.env is missing credentials. Restore the original .env; setup never regenerates existing passwords.')
    password = values['STARLIGHTS_SA_PASSWORD']
    if len(password) < 8 or sum(bool(re.search(pattern, password)) for pattern in
                               (r'[A-Z]', r'[a-z]', r'[0-9]', r'[^A-Za-z0-9]')) < 3:
        raise SetupError('STARLIGHTS_SA_PASSWORD does not meet SQL Server complexity requirements. '
                         'For an existing database, restore its original password rather than inventing a new one.')
    return values


def new_env(root):
    data = root / 'data'
    if data.is_symlink() or (data.exists() and any(data.iterdir())):
        raise SetupError('Existing data was found without .env. Restore the matching .env from your backup; '
                         'setup will not generate credentials for an existing installation.')
    return {'STARLIGHTS_SA_PASSWORD': 'Sl' + secrets.token_hex(24) + '9',
            'STARLIGHTS_ADMIN_KEY': secrets.token_hex(32),
            'STARLIGHTS_MASTER_PASSWORD': secrets.token_hex(24),
            'STARLIGHTS_PORT': '8093',
            'COMPOSE_PROJECT_NAME': 'starlights-' + hashlib.sha256(str(root).encode()).hexdigest()[:10]}


def write_env(root, values):
    # Link an fsynced, private file into place atomically, without replacing any existing .env.
    fd, name = tempfile.mkstemp(prefix='.setup-', suffix='.tmp', dir=root)
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write('# Generated by setup.sh. Keep this file private and back it up with data/.\n')
            stream.writelines(f'{key}={value}\n' for key, value in values.items())
            stream.flush()
            os.fsync(stream.fileno())
        os.link(name, root / '.env')
        directory = os.open(root, os.O_RDONLY)
        try:
            os.fsync(directory)
        finally:
            os.close(directory)
    finally:
        os.unlink(name)


class Installer:
    def __init__(self, root, args):
        self.root = root.resolve()
        self.args = args
        self.values = {}
        self.command_env = dict(os.environ)
        self.compose = []
        self.project = ''
        self.port = 8093
        self.existing = []
        self.timeouts = {}
        for name, default in (('BUILD', 1800), ('START', 300), ('HEALTH', 180), ('CONTENT', 1800)):
            value = os.environ.get(f'STARLIGHTS_SETUP_{name}_TIMEOUT', str(default))
            if not value.isdigit() or not 1 <= int(value) <= 86400:
                raise SetupError(f'STARLIGHTS_SETUP_{name}_TIMEOUT must be 1–86400 seconds.')
            self.timeouts[name] = int(value)

    def run(self, command, timeout=30):
        # Do not forward subprocess output: Compose/build errors can echo credentials/configuration.
        # Capture in a private anonymous file to avoid unbounded RAM use during a build.
        with tempfile.TemporaryFile() as output, tempfile.TemporaryFile() as errors:
            process = subprocess.Popen(command, cwd=self.root, env=self.command_env,
                                       stdout=output, stderr=errors, start_new_session=True)
            try:
                code = process.wait(timeout=timeout)
            except (subprocess.TimeoutExpired, KeyboardInterrupt):
                os.killpg(process.pid, signal.SIGTERM)
                try:
                    process.wait(timeout=5)
                except subprocess.TimeoutExpired:
                    os.killpg(process.pid, signal.SIGKILL)
                    process.wait()
                raise
            output.seek(0)
            if code:
                raise SetupError(f'Command failed (exit {code}); raw command output is withheld to protect credentials.')
            return output.read().decode('utf-8', errors='replace')

    def preflight(self):
        if platform.system() != 'Linux' or platform.machine().lower() not in ('x86_64', 'amd64'):
            raise SetupError('Use x86-64 Linux, or x86-64 Windows with a WSL2 Linux distribution. ARM is unsupported.')
        if 'microsoft' in platform.release().lower():
            if 'wsl2' not in platform.release().lower():
                raise SetupError('WSL1 is unsupported. Convert this distribution to WSL2 (see installation.md).')
            # Covers Windows drives, UNC mounts and custom DrvFS mountpoints.
            fs = subprocess.check_output(['stat', '-f', '-c', '%T', str(self.root)], text=True,
                                         stderr=subprocess.DEVNULL, timeout=10).strip()
            if fs in ('9p', 'drvfs', 'cifs', 'smb2') or str(self.root).startswith('/mnt/'):
                raise SetupError('Clone into your WSL Linux home (for example ~/starlights), not a Windows drive or network share.')
        if not os.access(self.root, os.W_OK | os.X_OK):
            raise SetupError('The deploy directory is not writable by your user. Use a checkout you own.')
        if not shutil.which('docker'):
            raise SetupError('Docker is missing. Install Docker Engine + Compose on Linux, or enable Docker Desktop WSL integration.')
        try:
            self.run(['docker', 'compose', 'version'])
        except SetupError as exc:
            raise SetupError('Docker Compose is unavailable. Install the Compose plugin; legacy docker-compose is unsupported.') from exc
        # Reject remote engines: bind mounts and port checks must refer to this host.
        context = json.loads(self.run(['docker', 'context', 'inspect']))[0]
        host = os.environ.get('DOCKER_HOST') or context['Endpoints']['docker']['Host']
        if not host.startswith('unix://'):
            raise SetupError('Use a local Docker engine (Unix socket), not a remote Docker context or DOCKER_HOST.')
        try:
            info = json.loads(self.run(['docker', 'info', '--format', '{{json .}}']))
        except SetupError as exc:
            raise SetupError('Cannot reach Docker. Start Docker / Docker Desktop and check your user can run docker info. '
                             'On Windows enable this distribution under Settings > Resources > WSL Integration. '
                             'Do not run setup with sudo.') from exc
        if info.get('OSType') != 'linux' or info.get('Architecture') not in ('x86_64', 'amd64'):
            raise SetupError('Docker must run x86-64 Linux containers. Switch Docker Desktop to Linux containers.')
        if int(info.get('MemTotal', 0)) < 3.5 * GIB:
            raise SetupError('Docker needs at least 4 GB RAM (8 GB recommended). Increase the VM/WSL memory allocation.')
        memory = dict(line.split(':', 1) for line in Path('/proc/meminfo').read_text().splitlines())
        available = int(memory['MemAvailable'].strip().split()[0]) * 1024
        if available < 2 * GIB:
            emit('Warning: less than 2 GB RAM is currently available. Builds or SQL Server may run out of memory.')
        paths = [self.root]
        docker_root = Path(info.get('DockerRootDir', '/var/lib/docker'))
        if os.access(docker_root, os.R_OK | os.X_OK):
            paths.append(docker_root)
        else:
            emit('Docker image storage cannot be checked from here; ensure it has at least 10 GB free (20 GB recommended).')
        for path in paths:
            if shutil.disk_usage(path).free < 10 * GIB:
                raise SetupError('At least 10 GB free disk is required for source, images, build cache and content; 20 GB is recommended.')
        self.values = read_env(self.root / '.env') if (self.root / '.env').exists() or (self.root / '.env').is_symlink() else new_env(self.root)
        if self.args.port is not None:
            if (self.root / '.env').exists() and self.values.get('STARLIGHTS_PORT', '8093') != str(self.args.port):
                raise SetupError('For an existing installation, change STARLIGHTS_PORT in .env; --port is for first setup only.')
            self.values['STARLIGHTS_PORT'] = str(self.args.port)
        port = self.values.get('STARLIGHTS_PORT', '8093') or '8093'
        if not port.isdigit() or not 1024 <= int(port) <= 65535:
            raise SetupError('STARLIGHTS_PORT in .env must be a number from 1024 to 65535 (default 8093).')
        self.port = int(port)
        # Preserve the original Compose default for installations predating this installer.
        self.project = self.values.get('COMPOSE_PROJECT_NAME') or re.sub('[^a-z0-9_-]', '', self.root.name.lower()).lstrip('_-')
        if not re.fullmatch('[a-z0-9][a-z0-9_-]*', self.project):
            raise SetupError('COMPOSE_PROJECT_NAME must contain lowercase letters, numbers, underscores or hyphens.')
        # Shell overrides must not silently diverge from the credentials used by maintenance tools.
        for key, value in os.environ.items():
            if (key.startswith('COMPOSE_') or key.startswith('STARLIGHTS_')) and not key.startswith('STARLIGHTS_SETUP_'):
                if key not in self.values or self.values[key] != value:
                    raise SetupError(f'Unset shell variable {key}; configure this installation in deploy/.env instead.')
        self.command_env.update(self.values)
        self.command_env['COMPOSE_PROJECT_NAME'] = self.project
        self.compose = ['docker', 'compose', '--project-directory', str(self.root), '--env-file', '/dev/null',
                        '-f', str(self.root / 'docker-compose.yml'), '-p', self.project]
        self.run(self.compose + ['config', '--quiet'])
        # Inspect only containers in our project. Never act on a same-named project in another checkout.
        ids = self.run(['docker', 'ps', '-aq', '--filter', f'label=com.docker.compose.project={self.project}']).split()
        if ids:
            self.existing = json.loads(self.run(['docker', 'inspect', *ids]))
        for container in self.existing:
            directory = container.get('Config', {}).get('Labels', {}).get('com.docker.compose.project.working_dir')
            if directory != str(self.root):
                raise SetupError('This Compose project belongs to a different directory. Do not reuse its name; '
                                 'choose a unique COMPOSE_PROJECT_NAME in the new installation’s .env.')
        self.check_paths()
        self.check_port()
        emit('Prerequisite checks passed: local Docker/Compose, x86-64 Linux, memory, disk, configuration and port.')

    def check_paths(self):
        data = self.root / 'data'
        if ',' in str(data):
            raise SetupError('The installation path contains a comma, which Docker bind mounts cannot parse. Use a path without commas.')
        for path in (data, *(data / name for name in FOLDERS)):
            if path.is_symlink() or (path.exists() and not path.is_dir()):
                raise SetupError(f'{path.name} must be a directory, not a symlink or file. No permissions were changed.')
        marker = data / '.installer-project'
        if marker.is_symlink() or (marker.exists() and marker.read_text().strip() != self.project):
            raise SetupError('This data directory is assigned to a different Compose project. Restore the original '
                             'COMPOSE_PROJECT_NAME; do not start a second database against the same files.')

    def check_port(self):
        # An existing web container can legitimately own the configured port on a repeated run.
        for container in self.existing:
            if (container['Config']['Labels'].get('com.docker.compose.service') == 'starlights-web'
                    and container.get('State', {}).get('Running')):
                bindings = container.get('NetworkSettings', {}).get('Ports', {}).get('80/tcp') or []
                if any(binding.get('HostPort') == str(self.port) for binding in bindings):
                    return
        for family, address in ((socket.AF_INET, ('0.0.0.0', self.port)), (socket.AF_INET6, ('::', self.port))):
            try:
                with socket.socket(family, socket.SOCK_STREAM) as sock:
                    if family == socket.AF_INET6:
                        sock.setsockopt(socket.IPPROTO_IPV6, socket.IPV6_V6ONLY, 1)
                    sock.bind(address)
            except OSError as exc:
                if family == socket.AF_INET6 and exc.errno in (errno.EAFNOSUPPORT, errno.EADDRNOTAVAIL, errno.EPROTONOSUPPORT):
                    continue
                raise SetupError(f'Port {self.port} is unavailable. Choose a free STARLIGHTS_PORT in .env '
                                 '(or use ./setup.sh --port 8094 for a new install); '
                                 'do not stop another service to free it.') from exc

    def prepare_folders(self):
        data = self.root / 'data'
        if not data.exists():
            data.mkdir(mode=0o755)
            data.chmod(0o755)
        marker = data / '.installer-project'
        if not marker.exists():
            with marker.open('x') as stream:
                stream.write(self.project + '\n')
        # Root helper is restricted to this install's bind mount, with no network or privilege escalation.
        # Only empty directories may be assigned an owner. Never recursively chown existing user data.
        script = '''set -eu
for item in portraits homebrew content lore mssql; do
    owner=1654:1654; [ "$item" != mssql ] || owner=10001:0
    if [ -z "$(ls -A "/d/$item")" ]; then chown "$owner" "/d/$item"; chmod 755 "/d/$item"; fi
done
'''
        for name in FOLDERS:
            folder = data / name
            if not folder.exists():
                folder.mkdir(mode=0o755)
                folder.chmod(0o755)
        self.run(['docker', 'run', '--rm', '--network', 'none', '--security-opt', 'no-new-privileges',
                  '--mount', f'type=bind,src={data},dst=/d', 'alpine:3.21', 'sh', '-c', script], timeout=120)
        # Actual write probes as the container UIDs catch ACL/rootless/bind-mount permission problems.
        for uid, folders in (('1654:1654', ['portraits', 'homebrew', 'content', 'lore']), ('10001:0', ['mssql'])):
            probe = 'set -eu; for p; do f=$(mktemp "/d/$p/.setup-XXXXXX"); rm "$f"; done'
            self.run(['docker', 'run', '--rm', '--network', 'none', '--security-opt', 'no-new-privileges',
                      '--user', uid, '--mount', f'type=bind,src={data},dst=/d',
                      'alpine:3.21', 'sh', '-c', probe, 'probe', *folders], timeout=30)

    def request(self, path, data=None, timeout=10, authenticated=False):
        headers = {'Content-Type': 'application/json'}
        if authenticated:
            headers['X-Admin-Key'] = self.values['STARLIGHTS_ADMIN_KEY']
        req = urllib.request.Request(f'http://127.0.0.1:{self.port}{path}',
                                     data=None if data is None else json.dumps(data).encode(), headers=headers)
        # Local requests must never send credentials through a configured HTTP proxy or a redirect.
        class NoRedirect(urllib.request.HTTPRedirectHandler):
            def redirect_request(self, req, fp, code, msg, headers, newurl):
                return None
        opener = urllib.request.build_opener(urllib.request.ProxyHandler({}), NoRedirect())
        with opener.open(req, timeout=timeout) as response:
            return json.load(response)

    def health(self):
        deadline = time.monotonic() + self.timeouts['HEALTH']
        while time.monotonic() < deadline:
            try:
                self.request('/api/characters/creation-options', timeout=min(5, max(.1, deadline - time.monotonic())))
                return
            except (OSError, ValueError):
                time.sleep(min(2, max(0, deadline - time.monotonic())))
        raise SetupError('The web/API health check timed out. Check SQL Server and migration status with '
                         '`docker compose ps -a`; see docs/installation.md before inspecting logs.')

    def content(self):
        deadline = time.monotonic() + self.timeouts['CONTENT']
        def status():
            return self.request('/api/admin/content-sources', authenticated=True,
                                timeout=min(10, max(.1, deadline - time.monotonic())))
        state = status()
        if not state.get('selfManaged'):
            raise SetupError('Content is externally managed. Use --skip-content and follow your administrator’s instructions.')
        job = state['job']
        # Server-side success persists across API restarts. Never refresh/reprocess existing characters on rerun.
        if not job['running'] and (job.get('succeeded') is True or state.get('status', {}).get('lastSuccessAt')):
            emit('Content has already been installed; leaving it unchanged.')
            return
        if not job['running']:
            try:
                self.request('/api/admin/content-sources/update', {'force': False}, authenticated=True,
                             timeout=min(10, max(.1, deadline - time.monotonic())))
            except urllib.error.HTTPError as exc:
                if exc.code != 409:  # another browser/installer started the job: attach rather than resubmit
                    raise
        emit('Waiting for content import. Its progress is visible on the Content page.')
        while time.monotonic() < deadline:
            state = status()
            job = state['job']
            if not job['running']:
                if job.get('succeeded') is True:
                    emit('Content import completed.')
                    return
                raise SetupError('Content import did not complete successfully.')
            time.sleep(min(3, max(0, deadline - time.monotonic())))
        raise SetupError('Content import wait timed out; the server job may still be running.')

    def install(self):
        stage = 'prerequisite checks'
        try:
            self.preflight()
            if self.args.check:
                emit('Check only: no files, containers or content were changed.')
                return 0
            if not (self.root / '.env').exists():
                write_env(self.root, self.values)
                emit('Created private deploy/.env. Credentials are never printed; back up this file with data/.')
            stage = 'data directory permissions'
            self.prepare_folders()
            stage = 'image build'
            # Existing healthy/stopped containers retain their images; setup is not an update tool.
            services = {c.get('Config', {}).get('Labels', {}).get('com.docker.compose.service') for c in self.existing}
            expected = {'starlights-db', 'starlights-api', 'starlights-web',
                        'starlights-migrate-elements', 'starlights-migrate-characters'}
            if not expected.issubset(services):
                emit(f'Building Starlights (up to {self.timeouts["BUILD"]} seconds). This can take a while on the first run.')
                if shutil.which('git'):
                    try:
                        self.command_env['STARLIGHTS_COMMIT'] = self.run(['git', 'rev-parse', '--short', 'HEAD']).strip() or 'unknown'
                    except (SetupError, subprocess.TimeoutExpired):
                        self.command_env['STARLIGHTS_COMMIT'] = 'unknown'
                self.run(self.compose + ['build', '--quiet'], timeout=self.timeouts['BUILD'])
            else:
                emit('Existing installation found; keeping its containers and images.')
            stage = 'container startup / database migrations'
            emit(f'Starting this installation (up to {self.timeouts["START"]} seconds).')
            self.run(self.compose + ['up', '-d', '--no-build', '--no-recreate'], timeout=self.timeouts['START'])
            stage = 'web/API readiness'
            self.health()
            emit(f'Open http://localhost:{self.port} on this computer (also in your Windows browser with Docker Desktop).')
            emit(f'From another device on your home network: http://<server-LAN-IP>:{self.port} (replace <server-LAN-IP>).')
            emit('The admin password is STARLIGHTS_MASTER_PASSWORD in deploy/.env. Use the key button in the header.')
            if self.args.skip_content:
                emit('Content setup skipped. Use the Content page to install it before creating characters.')
            else:
                stage = 'content import'
                self.content()
            emit('Setup complete. Keep .env and data/ together; rerunning setup does not reset them.')
            emit('Back up your group\'s data (characters, campaigns, homebrew, portraits) regularly, from this deploy folder:')
            emit('  maintenance/backup.sh            (copy the folder it makes in data/backups/ to another disk too)')
            emit('Restoring and updating: maintenance/restore.sh and maintenance/update.sh; see docs/maintenance.md.')
            return 0
        except (SetupError, OSError, ValueError, KeyError, subprocess.SubprocessError) as exc:
            # Only our own messages are safe to print; HTTP/Compose errors may contain secrets or response bodies.
            reason = str(exc) if isinstance(exc, SetupError) else 'Operation failed or timed out; diagnostic payloads are withheld.'
            emit(f'Error during {stage}: {reason}')
            if stage == 'content import':
                emit('Starlights is running, but content setup is incomplete. Check the Content page for download/import '
                     'errors and GitHub connectivity. Rerun ./setup.sh to attach to or retry the job; '
                     'a running server job is not cancelled by this installer. No success was recorded by setup.')
                return 2
            emit('Fix the reported problem and rerun ./setup.sh in this same directory. Preserve .env and data/. '
                 'See docs/installation.md for troubleshooting. Setup does not roll back migrations.')
            return 1


def main():
    parser = argparse.ArgumentParser(description='Install Starlights using local Docker. Linux or Windows through WSL2.')
    parser.add_argument('--check', action='store_true', help='check prerequisites only; do not change files or containers')
    parser.add_argument('--skip-content', action='store_true', help='start the app without downloading/importing content')
    parser.add_argument('--port', type=int, help='browser port for a new installation (default 8093)')
    args = parser.parse_args()
    os.umask(0o077)
    root = Path(__file__).resolve().parent
    try:
        # Linux directory flock requires no lock file; released by the kernel even after an interruption.
        lock = os.open(root, os.O_RDONLY)
        try:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            return Installer(root, args).install()
        finally:
            os.close(lock)
    except BlockingIOError:
        emit('Another setup is running in this directory. Wait for it to finish before retrying.')
        return 1
    except KeyboardInterrupt:
        emit('Setup interrupted. Keep .env and data/ and rerun ./setup.sh. Any server-side content job may still be running.')
        return 130
    except (SetupError, OSError) as exc:
        emit(str(exc) if isinstance(exc, SetupError) else 'Cannot lock/read the install directory. Use a writable checkout you own.')
        return 1


if __name__ == '__main__':
    sys.exit(main())
